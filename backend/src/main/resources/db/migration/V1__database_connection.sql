CREATE TABLE database_connection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 name VARCHAR(120) NOT NULL,
 description VARCHAR(1000), host VARCHAR(253) NOT NULL,
 port INTEGER NOT NULL CHECK (port BETWEEN 1 AND 65535),
 initial_database VARCHAR(63) NOT NULL, username VARCHAR(128) NOT NULL,
 encrypted_password TEXT NOT NULL, ssl_enabled BOOLEAN NOT NULL,
 active BOOLEAN NOT NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
