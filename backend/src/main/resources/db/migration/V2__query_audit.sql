CREATE TABLE query_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 execution_id UUID NOT NULL,
 connection_id BIGINT REFERENCES database_connection(id) ON DELETE SET NULL,
 connection_name VARCHAR(120) NOT NULL,
 database VARCHAR(63) NOT NULL,
 executed_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(16) NOT NULL,
 execution_time_ms BIGINT NOT NULL,
 row_count INTEGER NOT NULL,
 query_fingerprint VARCHAR(64) NOT NULL,
 error_message VARCHAR(1000)
);
CREATE INDEX query_audit_execution_idx ON query_audit(execution_id);
CREATE INDEX query_audit_executed_at_idx ON query_audit(executed_at);
